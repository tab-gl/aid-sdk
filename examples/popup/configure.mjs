import { readFile, writeFile } from 'node:fs/promises';

const envFile = new URL('./.env', import.meta.url);
const outputFile = new URL('./config.local.js', import.meta.url);

async function readEnvFile() {
  let text;
  try {
    text = await readFile(envFile, 'utf8');
  } catch (error) {
    if (error?.code === 'ENOENT') return {};
    throw error;
  }

  const values = {};
  for (const [index, rawLine] of text.split(/\r?\n/).entries()) {
    let line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    if (line.startsWith('export ')) line = line.slice('export '.length).trim();
    const separator = line.indexOf('=');
    if (separator < 1) throw new Error(`Invalid .env entry on line ${index + 1}; expected KEY=value`);
    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if (!/^[A-Z][A-Z0-9_]*$/.test(key)) {
      throw new Error(`Invalid environment variable name on line ${index + 1}`);
    }
    if ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

function requiredValue(environment, key) {
  const value = environment[key]?.trim();
  if (!value) throw new Error(`Set ${key} in examples/popup/.env or the process environment.`);
  return value;
}

function parseWebUrl(value, name, { allowPath }) {
  let url;
  try {
    url = new URL(value);
  } catch (error) {
    throw new Error(`${name} must be an absolute URL.`, { cause: error });
  }
  const localHosts = new Set(['localhost', '127.0.0.1', '[::1]']);
  const secure = url.protocol === 'https:' ||
    (url.protocol === 'http:' && localHosts.has(url.hostname.toLowerCase()));
  if (!secure || url.username || url.password || url.search || url.hash) {
    throw new Error(`${name} must use HTTPS (or HTTP on localhost) and contain no credentials, query, or fragment.`);
  }
  if (!allowPath && url.pathname !== '/') {
    throw new Error(`${name} must be an origin only, for example http://localhost:8000.`);
  }
  return url;
}

const fileValues = await readEnvFile();
const environment = { ...fileValues, ...process.env };
const issuerUrl = parseWebUrl(requiredValue(environment, 'ACE_ID_ISSUER'), 'ACE_ID_ISSUER', { allowPath: true });
const clientId = requiredValue(environment, 'ACE_ID_CLIENT_ID');
const appUrl = parseWebUrl(
  environment.ACE_ID_APP_ORIGIN?.trim() || 'http://localhost:8000',
  'ACE_ID_APP_ORIGIN',
  { allowPath: false },
);
if (appUrl.pathname !== '/' || appUrl.search) {
  throw new Error('ACE_ID_APP_ORIGIN must be an origin only, for example http://localhost:8000.');
}

const appOrigin = appUrl.origin;
const popupRedirectUri = new URL('/examples/popup/callback.html', appOrigin).toString();
const redirectUri = new URL('/examples/popup/redirect-callback.html', appOrigin).toString();
const config = {
  issuer: issuerUrl.toString().replace(/\/+$/, ''),
  clientId,
  popupRedirectUri,
  redirectUri,
  appUri: new URL('/examples/popup/index.html', appOrigin).toString(),
};

await writeFile(
  outputFile,
  `// Generated by configure.mjs. This file is ignored by Git.\nwindow.ACE_ID_DEMO_CONFIG = Object.freeze(${JSON.stringify(config, null, 2)});\n`,
  'utf8',
);
console.log(`Wrote ${outputFile.pathname}`);
console.log('Register these exact callback URIs with the public OIDC client:');
console.log(`  ${popupRedirectUri}`);
console.log(`  ${redirectUri}`);
console.log('If the issuer requires RP-initiated logout registration, also allow this post-logout URI:');
console.log(`  ${config.appUri}`);
console.log('The generated values are browser-visible. Do not use or add a client secret.');
